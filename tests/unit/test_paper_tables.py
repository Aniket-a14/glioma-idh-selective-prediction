def write_json(path: Path, document: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = (json.dumps(document, sort_keys=True) + "\n").encode()
    path.write_bytes(payload)
    path.with_name(path.name + ".sha256").write_text(
        hashlib.sha256(payload).hexdigest() + "  " + path.name + "\n"
    )


def prepare_run(root: Path) -> Path:
    """Reuse the existing prediction fixture builder; run both frozen writers."""
    spec = importlib.util.spec_from_file_location(
        "phase10_fixture", Path(__file__).with_name("test_phase10_analysis.py")
    )
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    artifacts = root / "artifacts"
    module._all_runs(artifacts)
    module._prepare(artifacts, "R1")
    with pytest.MonkeyPatch.context() as patch:
        patch.setenv("GLIOMA_ARTIFACT_ROOT", str(artifacts))
        analyze_phase09("R2", iterations=10, permutations=10)
        analyze_phase09_m6("R2", "R1", iterations=10, permutations=10)
        analyze_phase10("R2", ensemble_run_ids=module.MEMBERS, iterations=1000)
    # Counts-only, synthetic manifest with the actual writers' keys.
    cohort = {
        "retained_patient_count": 12,
        "excluded_patient_count": 3,
        "exclusion_reason_counts": {"qc:corrupt": 3},
    }
    write_json(
        root / "data/manifests/cohort_manifest_post_qc.json",
        {"cohorts": {"utsw": cohort}},
    )
    write_json(
        root / "data/manifests/exclusion_manifest_post_qc.json",
        {
            "cohorts": {
                "utsw": {"source_patient_count": 15, "reason_counts": {"qc:corrupt": 3}}
            }
        },
    )
    return artifacts / "experiments/R2"


@pytest.fixture(scope="module")
def frozen_run(tmp_path_factory: pytest.TempPathFactory) -> Path:
    return prepare_run(tmp_path_factory.mktemp("paper-input"))


def documents(directory: Path) -> tuple[dict[str, Any], dict[str, Any]]:
    return tuple(
        json.loads((directory / name).read_text())
        for name in ("phase09_analysis.json", "phase10_analysis.json")
    )  # type: ignore[return-value]


def test_tables_copy_all_stored_operating_points_and_absences(frozen_run: Path) -> None:
    phase09, _ = documents(frozen_run)
    risk, abstention = selective_tables(phase09, "utsw")
    for condition, cells in phase09["conditions"].items():
        for mechanism in ("M1", "M2", "M3", "M4", "M5", "M6"):
            rows = [
                row
                for row in risk.rows
                if row["condition"] == condition_label(condition)
                and row["mechanism"] == mechanism
            ]
            if cells[mechanism].get("absent"):
                assert len(rows) == 1
                assert rows[0]["risk"] == rows[0]["aurc"] == "absent"
                assert rows[0]["reason"] == cells[mechanism]["reason"]
            else:
                assert len(rows) == 5
                for row in rows:
                    cell = cells[mechanism]
                    op = cell["selective_risk_at_coverage"][str(row["target_coverage"])]
                    assert row["aurc"] == cell["aurc_mean_over_cutoffs"]
                    assert row["risk_lower"] == op["risk_95_interval"]["lower"]
                    assert row["risk_upper"] == op["risk_95_interval"]["upper"]
                    counterpart = next(
                        x
                        for x in abstention.rows
                        if all(
                            x[k] == row[k]
                            for k in ("condition", "mechanism", "target_coverage")
                        )
                    )
                    assert (
                        counterpart["rejected_but_correct_rate"]
                        == op["rejected_but_correct_rate"]
                    )


def test_coverage_labels_are_copied_not_reclassified(frozen_run: Path) -> None:
    phase09, _ = documents(frozen_run)
    phase09["conformal"]["full"]["carried_over"]["0.05"][
        "coverage_deviation_bootstrap"
    ]["deviation_label_band_0.07"] = "frozen sentinel"
    table = coverage_table(phase09, "utsw")
    assert len(table.rows) == 36
    assert any(row["deviation_label"] == "frozen sentinel" for row in table.rows)


def test_headline_quotes_selected_interval_and_preserves_hierarchy(
    frozen_run: Path,
) -> None:
    _, phase10 = documents(frozen_run)
    table = headline_table(phase10, "utsw")
    source = phase10["runs"]["R2"]
    row = table.rows[0]
    assert row["auroc_lower"] == source["auroc"][source["auroc"]["quoted"]]["lower"]
    assert row["auprc"] == source["auprc"]["point"]
    assert row["ece"] == source["calibration"]["M1"]["ece"]["point"]
    assert row["brier"] == source["calibration"]["M1"]["brier"]["point"]
    assert row["aurc"] == source["aurc_mean_over_cutoffs"]["point"]
    assert row["coverage"] == source["coverage"]
    assert all(
        row["auroc"] == "absent" for row in table.rows if row["run"] in ("R7", "R8")
    )


@pytest.mark.parametrize(
    "missing", ["calibration", "aurc_mean_over_cutoffs", "coverage", "ece", "brier"]
)
def test_auroc_builder_refuses_missing_companion(
    frozen_run: Path, missing: str
) -> None:
    _, phase10 = documents(frozen_run)
    run = phase10["runs"]["R2"]
    if missing in ("ece", "brier"):
        del run["calibration"]["M1"][missing]
    else:
        del run[missing]
    with pytest.raises(MetricHierarchyError):
        headline_table(phase10, "utsw")


